#!/usr/bin/env python3
"""Wildbound audio forge -- regenerate every SFX and music file, then analyse them.

Usage (from anywhere):
    python3 tools/audio_forge/build.py                  # everything + report.txt
    python3 tools/audio_forge/build.py --only hit_heavy title_theme
    python3 tools/audio_forge/build.py --sfx            # only SFX   (report still covers all files)
    python3 tools/audio_forge/build.py --music          # only music
    python3 tools/audio_forge/build.py --previews       # also write spectrogram PNGs (tools/audio_forge/previews/)
    python3 tools/audio_forge/build.py --report-only    # just re-analyse what is on disk

Output is deterministic: every recipe draws from an RNG seeded by its name.
"""

from __future__ import annotations

import argparse
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import numpy as np  # noqa: E402

import analyze as A  # noqa: E402
import synth as S  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SFX_DIR = os.path.join(ROOT, "assets", "audio", "sfx")
MUSIC_DIR = os.path.join(ROOT, "assets", "audio", "music")
PREVIEW_DIR = os.path.join(HERE, "previews")
REPORT = os.path.join(HERE, "report.txt")

MUSIC_PEAK_DB = -3.0     # music peaks around -3 dBFS ...
MUSIC_MAX_LUFS = -20.0   # ... but never louder than this integrated loudness (sits under the SFX)


def _preview(x: np.ndarray, sr: int, sub: str, name: str) -> None:
    d = A.analyze_signal(x, sr)
    title = f"{name}   {d['dur']:.2f}s   peak {d['peak_db']:.1f} dBFS   rms {d['rms_db']:.1f}   LUFS-M {d['lufs_m']:.1f}"
    A.spectrogram_png(x, sr, os.path.join(PREVIEW_DIR, sub, name + ".png"), title=title)


def sfx_job(name: str, previews: bool) -> tuple[str, float]:
    import sfx
    t0 = time.time()
    rec = sfx.REGISTRY[name]
    x = sfx.finalize(rec, rec.fn(S.rng_for("sfx", name)))
    S.write_wav(os.path.join(SFX_DIR, name + ".wav"), x, S.SFX_SR, loop=rec.loop)
    if previews:
        y, sr = S.read_wav(os.path.join(SFX_DIR, name + ".wav"))
        _preview(np.concatenate([y, y]) if rec.loop else y, sr, "sfx", name)
    return name, time.time() - t0


def master_music(x: np.ndarray, sr: int, loop: bool) -> np.ndarray:
    if not loop:
        x = S.trim(x, sr, lead_db=-50.0, tail_db=-58.0)
        x = S.fade(x, sr, 0.004, 0.6)
    x = S.normalize(x, MUSIC_PEAK_DB)
    lufs = A.loudness(x, sr, loop)[1]
    if lufs > MUSIC_MAX_LUFS:
        x = x * S.db2a(MUSIC_MAX_LUFS - lufs)
    return x


def music_job(name: str, previews: bool) -> tuple[str, float]:
    import music
    t0 = time.time()
    song = music.MUSIC[name]()
    x = master_music(music.render_song(song), song.sr, song.loop)
    path = os.path.join(MUSIC_DIR, name + ".wav")
    S.write_wav(path, x, song.sr, loop=song.loop)
    if previews:
        y, sr = S.read_wav(path)
        _preview(y, sr, "music", name)
    return name, time.time() - t0


def analyze_job(kind: str, name: str, loop: bool) -> tuple[str, str, dict, bool]:
    folder = SFX_DIR if kind == "sfx" else MUSIC_DIR
    path = os.path.join(folder, name + ".wav")
    if not os.path.exists(path):
        d = {"dur": 0.0, "peak_db": -120.0, "rms_db": -120.0, "lufs_m": -120.0, "lufs_i": -120.0, "dc": 0.0,
             "clip": 0, "problems": ["MISSING FILE"]}
        return kind, name, d, loop
    x, sr = S.read_wav(path)
    d = A.analyze_signal(x, sr, loop)
    d["problems"] = A.problems(d, loop, kind)
    expected_sr = S.SFX_SR if kind == "sfx" else S.MUSIC_SR
    if sr != expected_sr:
        d["problems"].append(f"sample rate {sr} != {expected_sr}")
    if loop and S.read_smpl_loop(path) is None:
        d["problems"].append("missing smpl loop chunk")
    return kind, name, d, loop


def catalogue() -> tuple[list[tuple[str, bool, str]], list[tuple[str, bool]]]:
    import music
    import sfx
    sfx_items = [(n, r.loop, r.cat) for n, r in sfx.REGISTRY.items()]
    music_items = [(n, music.MUSIC[n]().loop) for n in music.MUSIC]
    return sfx_items, music_items


def write_report(jobs: int) -> int:
    sfx_items, music_items = catalogue()
    cats = {n: c for n, _, c in sfx_items}
    tasks = [("sfx", n, lp) for n, lp, _ in sfx_items] + [("music", n, lp) for n, lp in music_items]
    with ProcessPoolExecutor(max_workers=jobs) as ex:
        results = list(ex.map(analyze_job, *zip(*tasks)))
    rows = []
    for kind, name, d, loop in results:
        sec = "SFX  (44100 Hz, mono, 16-bit PCM)" if kind == "sfx" else "MUSIC  (32000 Hz, mono, 16-bit PCM)"
        rows.append((sec, f"{name}.wav", d, loop))
    header = ("Wildbound audio forge -- analysis report\n"
              "Generated by tools/audio_forge/build.py (deterministic; re-run to regenerate).\n"
              "LUFS-M = max momentary loudness (400 ms, K-weighted), LUFS-I = gated integrated loudness;\n"
              "both approximate ITU-R BS.1770.  Loops carry a RIFF 'smpl' forward loop over the whole file.\n"
              f"Music mastering: peak {MUSIC_PEAK_DB:.0f} dBFS, integrated loudness capped at {MUSIC_MAX_LUFS:.0f} LUFS.")
    text = A.format_report(rows, header)
    # per-category summary for loudness consistency
    by_cat: dict[str, list[dict]] = {}
    for kind, name, d, loop in results:
        if kind == "sfx":
            by_cat.setdefault(cats[name], []).append(d)
    lines = ["SFX loudness by category (min / median / max LUFS-M; peak range dBFS)",
             "----------------------------------------------------------------------"]
    for cat, ds in sorted(by_cat.items()):
        lm = sorted(x["lufs_m"] for x in ds)
        pk = [x["peak_db"] for x in ds]
        lines.append(f"{cat:10s} n={len(ds):2d}   LUFS-M {lm[0]:6.1f} / {lm[len(lm) // 2]:6.1f} / {lm[-1]:6.1f}"
                     f"   peak {min(pk):6.1f} .. {max(pk):6.1f}")
    total_sfx_s = sum(d["dur"] for k, _, d, _ in results if k == "sfx")
    total_mus_s = sum(d["dur"] for k, _, d, _ in results if k == "music")
    lines.append("")
    lines.append(f"Totals: {len(sfx_items)} SFX ({total_sfx_s:.1f} s), {len(music_items)} music files ({total_mus_s:.1f} s).")
    text += "\n" + "\n".join(lines) + "\n"
    with open(REPORT, "w", encoding="utf-8") as fh:
        fh.write(text)
    return sum(len(d.get("problems", [])) for _, _, d, _ in results)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="+", help="build only these names (SFX or music)")
    ap.add_argument("--sfx", action="store_true", help="build only SFX")
    ap.add_argument("--music", action="store_true", help="build only music")
    ap.add_argument("--previews", action="store_true", help="write spectrogram PNGs to tools/audio_forge/previews/")
    ap.add_argument("--report-only", action="store_true", help="skip rendering, just analyse files on disk")
    ap.add_argument("--jobs", type=int, default=max(1, min(8, os.cpu_count() or 1)))
    args = ap.parse_args()

    os.makedirs(SFX_DIR, exist_ok=True)
    os.makedirs(MUSIC_DIR, exist_ok=True)
    import music
    import sfx

    t_start = time.time()
    if not args.report_only:
        music_names = list(music.MUSIC)
        sfx_names = list(sfx.REGISTRY)
        if args.only:
            unknown = [n for n in args.only if n not in music.MUSIC and n not in sfx.REGISTRY]
            if unknown:
                print("unknown names:", ", ".join(unknown))
                return 2
            music_names = [n for n in music_names if n in args.only]
            sfx_names = [n for n in sfx_names if n in args.only]
        if args.sfx and not args.music:
            music_names = []
        if args.music and not args.sfx:
            sfx_names = []
        with ProcessPoolExecutor(max_workers=args.jobs) as ex:
            futs = [ex.submit(music_job, n, args.previews) for n in music_names]
            futs += [ex.submit(sfx_job, n, args.previews) for n in sfx_names]
            for f in futs:
                name, dt = f.result()
                print(f"  built {name:28s} {dt:6.2f} s", flush=True)
    n_problems = write_report(args.jobs)
    print(f"report: {os.path.relpath(REPORT, ROOT)}  ({n_problems} problem(s) flagged)  "
          f"total {time.time() - t_start:.1f} s")
    return 0 if n_problems == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
